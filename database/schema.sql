-- =====================================================================
-- SMJ Jewellery Store Management System - PostgreSQL schema
-- Target: Neon PostgreSQL (PostgreSQL 15+)
--
-- This file is the canonical, up-to-date schema (run it on an empty database).
-- backend/migrations/*.sql build the same schema step by step and are applied by
-- `npm run db:migrate`; the test-suite checks that both produce identical structures.
--
-- 11 tables in schema "public":
--   users, customers, gold_rates, products, invoices, invoice_items,
--   wholesale_parties, stock_movements, wholesale_distributions,
--   wholesale_distribution_items, payments
--
-- Conventions: NUMERIC for money / weight, TIMESTAMPTZ for timestamps,
-- weights in grams (3 decimals), money in INR (2 decimals).
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. users  (application logins and roles)
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120)  NOT NULL,
    email           VARCHAR(255)  NOT NULL,
    password_hash   VARCHAR(255)  NOT NULL,
    mobile_number   VARCHAR(15),
    role            VARCHAR(20)   NOT NULL DEFAULT 'staff',
    is_active       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT users_email_lowercase_chk CHECK (email = lower(email)),
    CONSTRAINT users_role_chk CHECK (role IN ('admin', 'staff', 'party', 'shopkeeper', 'line_member'))
);

-- ---------------------------------------------------------------------
-- 2. customers  (retail customers, identified by mobile number)
-- ---------------------------------------------------------------------
CREATE TABLE customers (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120)  NOT NULL,
    email           VARCHAR(255),
    mobile_number   VARCHAR(10)   NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT customers_mobile_number_key UNIQUE (mobile_number),
    CONSTRAINT customers_mobile_format_chk CHECK (mobile_number ~ '^[0-9]{10}$'),
    CONSTRAINT customers_name_not_blank_chk CHECK (length(btrim(name)) > 0)
);
CREATE INDEX customers_name_idx ON customers (lower(name));

-- ---------------------------------------------------------------------
-- 3. gold_rates  (append-only history; latest effective row is "today's rate")
-- ---------------------------------------------------------------------
CREATE TABLE gold_rates (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gold_rate_per_gram    NUMERIC(12, 2) NOT NULL,
    silver_rate_per_gram  NUMERIC(12, 2) NOT NULL,
    effective_date        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_by            INTEGER        REFERENCES users (id) ON DELETE SET NULL,
    created_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT gold_rates_gold_positive_chk   CHECK (gold_rate_per_gram > 0),
    CONSTRAINT gold_rates_silver_positive_chk CHECK (silver_rate_per_gram > 0)
);
CREATE INDEX gold_rates_effective_idx ON gold_rates (effective_date DESC, id DESC);

-- ---------------------------------------------------------------------
-- 4. products  (inventory; quantity = pieces currently available in store,
--               weight = weight of ONE piece in grams)
-- ---------------------------------------------------------------------
CREATE TABLE products (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name    VARCHAR(150)   NOT NULL,
    category        VARCHAR(20)    NOT NULL,
    metal           VARCHAR(10)    NOT NULL DEFAULT 'gold',
    description     TEXT,
    weight          NUMERIC(10, 3) NOT NULL DEFAULT 0,
    quantity        INTEGER        NOT NULL DEFAULT 0,
    purchase_price  NUMERIC(12, 2) NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT products_category_chk CHECK (category IN ('Tumbler', 'Chain', 'Anklet', 'Ring')),
    CONSTRAINT products_metal_chk    CHECK (metal IN ('gold', 'silver')),
    CONSTRAINT products_weight_chk   CHECK (weight >= 0),
    CONSTRAINT products_quantity_chk CHECK (quantity >= 0),
    CONSTRAINT products_price_chk    CHECK (purchase_price >= 0)
);
CREATE UNIQUE INDEX products_name_category_key ON products (lower(product_name), category);
CREATE INDEX products_category_idx ON products (category);

-- ---------------------------------------------------------------------
-- 5. wholesale_parties  (parties, shopkeepers/owners and line members)
--    (created before invoices because wholesale invoices reference it)
-- ---------------------------------------------------------------------
CREATE TABLE wholesale_parties (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(150)  NOT NULL,
    mobile_number   VARCHAR(10)   NOT NULL,
    email           VARCHAR(255),
    address         TEXT,
    party_type      VARCHAR(20)   NOT NULL,
    is_active       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT wholesale_parties_type_chk   CHECK (party_type IN ('party', 'shopkeeper', 'line_member')),
    CONSTRAINT wholesale_parties_mobile_chk CHECK (mobile_number ~ '^[0-9]{10}$'),
    CONSTRAINT wholesale_parties_mobile_type_key UNIQUE (mobile_number, party_type)
);
CREATE INDEX wholesale_parties_type_idx ON wholesale_parties (party_type);

-- ---------------------------------------------------------------------
-- 6. invoices  (retail -> customer, wholesale -> wholesale party)
--    Amounts are snapshots taken at billing time and never recalculated.
-- ---------------------------------------------------------------------
CREATE SEQUENCE retail_invoice_seq;
CREATE SEQUENCE wholesale_invoice_seq;

CREATE TABLE invoices (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number        VARCHAR(30)    NOT NULL,
    customer_id           INTEGER        REFERENCES customers (id) ON DELETE RESTRICT,
    party_id              INTEGER        REFERENCES wholesale_parties (id) ON DELETE RESTRICT,
    invoice_type          VARCHAR(10)    NOT NULL,
    invoice_date          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    gold_rate_id          INTEGER        REFERENCES gold_rates (id) ON DELETE RESTRICT,
    gold_rate_per_gram    NUMERIC(12, 2) NOT NULL,
    silver_rate_per_gram  NUMERIC(12, 2) NOT NULL,
    total_weight          NUMERIC(12, 3) NOT NULL DEFAULT 0,
    gold_amount           NUMERIC(14, 2) NOT NULL DEFAULT 0,
    making_charges        NUMERIC(14, 2) NOT NULL DEFAULT 0,
    subtotal              NUMERIC(14, 2) NOT NULL DEFAULT 0,
    item_discount         NUMERIC(14, 2) NOT NULL DEFAULT 0,
    overall_discount      NUMERIC(14, 2) NOT NULL DEFAULT 0,
    discount              NUMERIC(14, 2) NOT NULL DEFAULT 0,
    gst_rate              NUMERIC(5, 2)  NOT NULL DEFAULT 0,
    gst_amount            NUMERIC(14, 2) NOT NULL DEFAULT 0,
    grand_total           NUMERIC(14, 2) NOT NULL DEFAULT 0,
    amount_paid           NUMERIC(14, 2) NOT NULL DEFAULT 0,
    payment_status        VARCHAR(10)    NOT NULL DEFAULT 'unpaid',
    notes                 TEXT,
    created_by            INTEGER        REFERENCES users (id) ON DELETE SET NULL,
    created_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT invoices_invoice_number_key UNIQUE (invoice_number),
    CONSTRAINT invoices_type_chk CHECK (invoice_type IN ('retail', 'wholesale')),
    CONSTRAINT invoices_owner_chk CHECK (
        (invoice_type = 'retail'    AND customer_id IS NOT NULL AND party_id IS NULL) OR
        (invoice_type = 'wholesale' AND party_id IS NOT NULL    AND customer_id IS NULL)
    ),
    CONSTRAINT invoices_payment_status_chk CHECK (payment_status IN ('paid', 'partial', 'unpaid')),
    CONSTRAINT invoices_amounts_chk CHECK (
        total_weight >= 0 AND gold_amount >= 0 AND making_charges >= 0 AND subtotal >= 0
        AND item_discount >= 0 AND overall_discount >= 0 AND grand_total >= 0
    ),
    CONSTRAINT invoices_discount_sum_chk CHECK (discount = item_discount + overall_discount),
    CONSTRAINT invoices_gst_chk CHECK (gst_rate >= 0 AND gst_rate <= 28 AND gst_amount >= 0),
    -- GST (optional) is charged on the taxable value: subtotal - discount
    CONSTRAINT invoices_total_chk CHECK (grand_total = subtotal - discount + gst_amount),
    CONSTRAINT invoices_paid_chk CHECK (amount_paid >= 0 AND amount_paid <= grand_total)
);
CREATE INDEX invoices_customer_idx ON invoices (customer_id);
CREATE INDEX invoices_party_idx    ON invoices (party_id);
CREATE INDEX invoices_date_idx     ON invoices (invoice_date DESC);
CREATE INDEX invoices_type_date_idx ON invoices (invoice_type, invoice_date DESC);
CREATE INDEX invoices_created_by_idx ON invoices (created_by);

-- ---------------------------------------------------------------------
-- 7. invoice_items
-- ---------------------------------------------------------------------
CREATE TABLE invoice_items (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id      INTEGER        NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    product_id      INTEGER        REFERENCES products (id) ON DELETE SET NULL,
    product_name    VARCHAR(150)   NOT NULL,
    category        VARCHAR(20)    NOT NULL,
    metal           VARCHAR(10)    NOT NULL DEFAULT 'gold',
    description     TEXT,
    weight          NUMERIC(10, 3) NOT NULL,
    quantity        INTEGER        NOT NULL,
    gold_rate       NUMERIC(12, 2) NOT NULL,
    gold_amount     NUMERIC(14, 2) NOT NULL,
    making_charges  NUMERIC(14, 2) NOT NULL DEFAULT 0,
    discount        NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total_amount    NUMERIC(14, 2) NOT NULL,
    CONSTRAINT invoice_items_category_chk CHECK (category IN ('Tumbler', 'Chain', 'Anklet', 'Ring')),
    CONSTRAINT invoice_items_metal_chk    CHECK (metal IN ('gold', 'silver')),
    CONSTRAINT invoice_items_weight_chk   CHECK (weight > 0),
    CONSTRAINT invoice_items_quantity_chk CHECK (quantity > 0),
    CONSTRAINT invoice_items_rate_chk     CHECK (gold_rate > 0),
    CONSTRAINT invoice_items_amounts_chk  CHECK (gold_amount >= 0 AND making_charges >= 0 AND discount >= 0),
    CONSTRAINT invoice_items_discount_chk CHECK (discount <= gold_amount + making_charges),
    CONSTRAINT invoice_items_total_chk    CHECK (total_amount = gold_amount + making_charges - discount)
);
CREATE INDEX invoice_items_invoice_idx ON invoice_items (invoice_id);
CREATE INDEX invoice_items_product_idx ON invoice_items (product_id);

-- ---------------------------------------------------------------------
-- 8. wholesale_distributions  (stock issued to a party / shopkeeper / line member)
-- ---------------------------------------------------------------------
CREATE TABLE wholesale_distributions (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id            INTEGER       NOT NULL REFERENCES wholesale_parties (id) ON DELETE RESTRICT,
    line_member_id      INTEGER       REFERENCES wholesale_parties (id) ON DELETE RESTRICT,
    issued_by           INTEGER       REFERENCES users (id) ON DELETE SET NULL,
    received_by         VARCHAR(120),
    total_items_issued  INTEGER       NOT NULL,
    distribution_date   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    last_return_date    TIMESTAMPTZ,
    status              VARCHAR(20)   NOT NULL DEFAULT 'open',
    purpose             VARCHAR(255),
    remarks             TEXT,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT wholesale_distributions_items_chk  CHECK (total_items_issued > 0),
    CONSTRAINT wholesale_distributions_status_chk CHECK (status IN ('open', 'partially_settled', 'closed'))
);
CREATE INDEX wholesale_distributions_party_idx ON wholesale_distributions (party_id);
CREATE INDEX wholesale_distributions_line_member_idx ON wholesale_distributions (line_member_id);
CREATE INDEX wholesale_distributions_date_idx  ON wholesale_distributions (distribution_date DESC);

-- ---------------------------------------------------------------------
-- 9. wholesale_distribution_items
--    remaining = quantity_issued - quantity_sold - quantity_returned  (never negative)
-- ---------------------------------------------------------------------
CREATE TABLE wholesale_distribution_items (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distribution_id     INTEGER        NOT NULL REFERENCES wholesale_distributions (id) ON DELETE CASCADE,
    product_id          INTEGER        NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
    quantity_issued     INTEGER        NOT NULL,
    quantity_sold       INTEGER        NOT NULL DEFAULT 0,
    quantity_returned   INTEGER        NOT NULL DEFAULT 0,
    weight              NUMERIC(12, 3) NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT wdi_issued_chk   CHECK (quantity_issued > 0),
    CONSTRAINT wdi_sold_chk     CHECK (quantity_sold >= 0),
    CONSTRAINT wdi_returned_chk CHECK (quantity_returned >= 0),
    CONSTRAINT wdi_balance_chk  CHECK (quantity_sold + quantity_returned <= quantity_issued),
    CONSTRAINT wdi_weight_chk   CHECK (weight >= 0),
    CONSTRAINT wdi_distribution_product_key UNIQUE (distribution_id, product_id)
);
CREATE INDEX wdi_product_idx ON wholesale_distribution_items (product_id);

-- ---------------------------------------------------------------------
-- 10. stock_movements  (append-only audit log of every stock change)
-- ---------------------------------------------------------------------
CREATE TABLE stock_movements (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        INTEGER        NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
    movement_type     VARCHAR(10)    NOT NULL,
    quantity          INTEGER        NOT NULL,
    weight            NUMERIC(12, 3) NOT NULL DEFAULT 0,
    unit_price        NUMERIC(12, 2),
    supplier_details  TEXT,
    from_party_id     INTEGER        REFERENCES wholesale_parties (id) ON DELETE SET NULL,
    to_party_id       INTEGER        REFERENCES wholesale_parties (id) ON DELETE SET NULL,
    reference_type    VARCHAR(30),
    reference_id      INTEGER,
    movement_date     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by        INTEGER        REFERENCES users (id) ON DELETE SET NULL,
    remarks           TEXT,
    created_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT stock_movements_type_chk     CHECK (movement_type IN ('inward', 'outward', 'sold', 'returned')),
    CONSTRAINT stock_movements_quantity_chk CHECK (quantity > 0),
    CONSTRAINT stock_movements_weight_chk   CHECK (weight >= 0),
    CONSTRAINT stock_movements_ref_type_chk CHECK (
        reference_type IS NULL OR reference_type IN ('stock_inward', 'distribution', 'invoice', 'adjustment')
    )
);
CREATE INDEX stock_movements_product_idx   ON stock_movements (product_id);
CREATE INDEX stock_movements_type_date_idx ON stock_movements (movement_type, movement_date DESC);
CREATE INDEX stock_movements_reference_idx ON stock_movements (reference_type, reference_id);
CREATE INDEX stock_movements_to_party_idx  ON stock_movements (to_party_id);
CREATE INDEX stock_movements_from_party_idx ON stock_movements (from_party_id);

-- ---------------------------------------------------------------------
-- 11. payments
-- ---------------------------------------------------------------------
CREATE TABLE payments (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id          INTEGER        NOT NULL REFERENCES invoices (id) ON DELETE RESTRICT,
    amount              NUMERIC(14, 2) NOT NULL,
    payment_method      VARCHAR(20)    NOT NULL,
    payment_date        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    payment_reference   VARCHAR(120),
    received_by         INTEGER        REFERENCES users (id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT payments_amount_chk CHECK (amount > 0),
    CONSTRAINT payments_method_chk CHECK (payment_method IN ('cash', 'card', 'upi', 'bank_transfer', 'cheque', 'other'))
);
CREATE INDEX payments_invoice_idx ON payments (invoice_id);
CREATE INDEX payments_date_idx    ON payments (payment_date DESC);

COMMIT;
